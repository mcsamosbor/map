/**
 * Справочник предметов, продаваемых в магазинах блоков.
 *
 * `id` (ItemId) используется одновременно:
 *  - как ключ записи в глобальной таблице `shop_items` (Supabase);
 *  - как значение в `BlockRawData.sale_items`.
 *
 * Моковых/стартовых предметов нет: справочник пустой и заполняется
 * картографами прямо на сайте, поэтому id — строка (uuid генерируется
 * в сторе при добавлении).
 */
export type ItemId = string;

/** Продаваемый предмет: за `price` талонов дают `count` единиц. */
export interface ItemData {
  id: ItemId;
  name: string;
  /** Сколько единиц предмета продаётся за `price` талонов. */
  count: number;
  /** Цена в талонах за `count` единиц. */
  price: number;
  /**
   * Иконка предмета как data URL (PNG до 64×64), загружается картографами:
   * при загрузке формат нормализуется в PNG, а картинка крупнее 64×64
   * автоматически уменьшается (без сглаживания — пиксель-арт чёткий).
   * Если не задана — иконки просто нет (ItemIcon ничего не рендерит).
   */
  icon?: string;
  /** Теги — слова, придумываемые картографами («Расходник», «Чертеж»…). */
  tags: string[];
}

/** Данные предмета без id (id генерируется в сторе при добавлении). */
export type NewItemData = Omit<ItemData, "id">;
